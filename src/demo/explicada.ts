const center = (radius: number, phi: number, theta: number, turn: number): Shot => ({
  target: { kind: 'center' },
  radius,
  phi,
  theta,
  turn,
  focus: false,
});
const belt = (
  id: number,
  radius: number,
  phi: number,
  theta: number,
  turn: number,
  focus: boolean,
): Shot => ({
  target: { kind: 'belt', id },
  radius,
  phi,
  theta,
  turn,
  focus,
});
const motor = (id: number, radius: number, theta: number, turn: number): Shot => ({
  target: { kind: 'motor', id },
  radius,
  phi: 0.7,
  theta,
  turn,
  focus: true,
});

